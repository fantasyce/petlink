import Foundation

@main struct AvatarRequestStateTests {
 static func task(_ id:String,_ state:String,_ time:Int64=1,_ requester:String="b",_ device:String="device-b")->AvatarRelayDTO {
  AvatarRelayDTO(task:AvatarTaskDTO(id:id,ownerID:"a",requesterID:requester,requesterDeviceID:device,ownerDeviceID:"device-a",provider:"claude",state:state,visitRevision:1,policyRevision:1,requestDigest:"digest",resultDigest:nil,createdAtMS:time,expiresAtMS:time+120000,errorCode:nil),request:nil,result:nil,peerKey:nil)
 }
 static func main() {
  var owner=AvatarOwnerNotice()
  owner.update([task("old","completed")],account:"a",device:"device-a")
  owner.set("old",message:"old answer")
  owner.update([task("old","completed"),task("new","pending_approval",2)],account:"a",device:"device-a")
  precondition(!owner.status.contains("old answer") && owner.status.contains("批准"))
  owner.set("old",message:"late failure")
  precondition(!owner.status.contains("late failure"))
  owner.update([task("new","expired",2)],account:"a",device:"device-a")
  precondition(owner.status.contains("过期"))
  owner.set("new",message:"late failure")
  precondition(owner.status.contains("过期"),"late callback overwrote terminal notice")
  owner.update([],account:"a",device:"device-a")
  precondition(owner.status.isEmpty)
  var view=AvatarRequestState()
  view.begin("failed-submit")
  view.submissionFailed("failed-submit",message:"network unavailable")
  precondition(view.state=="submission_failed","submission failure must release the waiting composer")
  _ = view.update([task("failed-submit","running")],account:"b",device:"device-b")
  view.complete("failed-submit",answer:"recovered",provider:"codex")
  precondition(view.answer=="recovered","a lost HTTP response must not discard an authoritative encrypted reply")
  view.begin("progressed-submit")
  _ = view.update([task("progressed-submit","pending_approval")],account:"b",device:"device-b")
  view.submissionFailed("progressed-submit",message:"lost HTTP response")
  _ = view.update([task("progressed-submit","completed")],account:"b",device:"device-b")
  view.complete("progressed-submit",answer:"already accepted",provider:"codex")
  precondition(view.answer=="already accepted","WebSocket progress must survive the POST response being lost")
  view.begin("one")
  _ = view.update([task("one","pending_approval")],account:"b",device:"device-b")
  precondition(view.status.contains("等待主人批准"))
  _ = view.update([task("one","rejected")],account:"b",device:"device-b")
  precondition(view.status.contains("拒绝") && !view.status.contains("等待"),"rejection leaves stale waiting status")
  _ = view.update([task("one","pending_approval")],account:"b",device:"device-b")
  precondition(view.status.contains("拒绝"),"late snapshot regressed terminal state")
  view.complete("one",answer:"late answer",provider:"codex")
  precondition(view.answer.isEmpty && view.state=="rejected","late result must not revive a rejected chat")
  for (state,word) in [("cancelled","取消"),("expired","过期"),("revoked","撤销"),("failed","失败")] {
   view.begin(state)
   _ = view.update([task(state,state)],account:"b",device:"device-b")
   precondition(view.status.contains(word) && view.answer.isEmpty)
  }
  view.begin("new")
  _ = view.update([task("old","completed"),task("new","running",2)],account:"b",device:"device-b")
  precondition(view.taskID=="new" && view.status.contains("正在回答"))
  view.complete("old",answer:"stale",provider:"claude")
  precondition(view.answer.isEmpty,"old result overwrote new question")
  view.complete("new",answer:"fresh",provider:"claude")
  _ = view.update([task("new","completed",2)],account:"b",device:"device-b")
  precondition(view.answer=="fresh" && view.status.contains("Claude Code"))
  view.begin("next")
  precondition(view.answer.isEmpty,"new submission retained prior answer")
  view.complete("next",answer:"",provider:"claude",errorCode:"AGENT_EXECUTION_FAILED")
  _ = view.update([task("next","completed")],account:"b",device:"device-b")
  precondition(view.status.contains("失败") && view.answer.isEmpty,"snapshot overwrote decrypted failure")
  var restored=AvatarRequestState()
  _ = restored.update([task("old","completed"),task("latest","rejected",2),task("foreign","running",5,"other"),task("other-device","running",6,"b","else")],account:"b",device:"device-b")
  precondition(restored.taskID=="latest" && restored.status.contains("拒绝"),"reconnect restored wrong request")
  var expiredResult=AvatarRequestState()
  _ = expiredResult.update([task("gone","completed")],account:"b",device:"device-b")
  precondition(expiredResult.status.contains("过期") && expiredResult.answer.isEmpty)
  print("Avatar request presentation: rejection / terminal states / stale snapshots / isolation / recovery PASS")
 }
}
